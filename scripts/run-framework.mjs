import { fileURLToPath } from 'node:url';
import { existsSync } from 'node:fs';
const root = fileURLToPath(new URL('../', import.meta.url));
process.chdir(root);
const [command, ...args] = process.argv.slice(2);
if (!['dev','build','start'].includes(command)) throw new Error('Usa dev, build o start.');
if (['dev','start'].includes(command) && args.some(value => value === '-H' || value.startsWith('--hostname'))) throw new Error('Este prototipo solo se inicia en 127.0.0.1.');
if (command !== 'build') await import('./prepare-local.mjs');
if (command === 'start' && !existsSync(fileURLToPath(new URL('../dist/server/index.js', import.meta.url)))) throw new Error('Primero ejecuta npm.cmd run build.');
const cli = new URL('../node_modules/vinext/dist/cli.js', import.meta.url);
process.argv = [process.execPath, fileURLToPath(cli), command, ...(['dev','start'].includes(command) ? ['--port','5173','--hostname','127.0.0.1'] : []), ...args];
await import(cli.href);
